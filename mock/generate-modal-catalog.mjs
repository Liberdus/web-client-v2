import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const productionHtml = await readFile(new URL('../index.html', import.meta.url), 'utf8');

function humanizeModalId(id) {
  return id
    .replace(/Modal$/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/^./, (character) => character.toUpperCase());
}

function modalCategory(id) {
  if (/chat|contact|friend|message|avatar|toll/i.test(id)) return 'Chat & People';
  if (/asset|send|receive|history|stake|farm|bridge|validator/i.test(id)) return 'Wallet & Assets';
  if (/account|sign|lock|secret|backup|import|migrate|launch|warning/i.test(id)) return 'Account & Security';
  if (/call|dateTime|duration|share|qr|googleDrive/i.test(id)) return 'Calls & Sharing';
  return 'App & Network';
}

function titleFromMarkup(markup, id) {
  const match = markup.match(/class="[^"]*modal-title[^"]*"[^>]*>\s*([^<]+?)\s*</);
  return match?.[1]?.trim() || humanizeModalId(id);
}

function productionRelativeMarkup(markup) {
  return markup.replace(/\b(src|href)="\.\//g, '$1="../');
}

function extractModals(html) {
  const tokens = [...html.matchAll(/<div\b[^>]*>|<\/div\s*>/gi)];
  const stack = [];
  const modals = [];

  for (const token of tokens) {
    if (/^<\/div/i.test(token[0])) {
      const opened = stack.pop();
      if (!opened) throw new Error('Production HTML contains an unmatched closing div');
      if (!opened?.modalId) continue;
      const markup = productionRelativeMarkup(html.slice(opened.start, token.index + token[0].length));
      modals.push({
        id: opened.modalId,
        title: titleFromMarkup(markup, opened.modalId),
        category: modalCategory(opened.modalId),
        markup,
      });
      continue;
    }

    const className = token[0].match(/\bclass="([^"]*)"/)?.[1] || '';
    const id = token[0].match(/\bid="([^"]+)"/)?.[1] || '';
    stack.push({
      start: token.index,
      modalId: className.split(/\s+/).includes('modal') ? id : '',
    });
  }

  const ids = modals.map(({ id }) => id);
  if (ids.some((id) => !id)) throw new Error('Every production modal must have an id');
  if (new Set(ids).size !== ids.length) throw new Error('Production modal ids must be unique');
  return modals.sort((left, right) => left.category.localeCompare(right.category) || left.title.localeCompare(right.title));
}

const catalog = extractModals(productionHtml);
const sourceHash = createHash('sha256').update(productionHtml).digest('hex');
const output = `/* Generated by mock/generate-modal-catalog.mjs. */\nwindow.MODAL_CATALOG_SOURCE = "${sourceHash}";\nwindow.MODAL_CATALOG = Object.freeze(${JSON.stringify(catalog, null, 2)});\n`;
await writeFile(new URL('./modal-catalog-data.js', import.meta.url), output);
console.log(`Generated ${catalog.length} modal previews`);
